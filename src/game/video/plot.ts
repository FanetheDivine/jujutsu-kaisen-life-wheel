export const ERA_ORDER = [
  '千年前平安时代',
  '400年前',
  '怀玉时期',
  '0卷时期',
  '剧情开始时',
  '涩谷事变时期',
  '死灭回游时期',
  '新宿决战时期',
  '68年后外传',
]

/** 时间点下标；录像没抽到时间点时按最早算，好让整条线都播。 */
export function eraIndex(pick: string | undefined): number {
  if (!pick) return 0
  const index = ERA_ORDER.indexOf(labelOf(pick))
  return index < 0 ? 0 : index
}

/** 穿越时间点晚于某个篇章时，那个篇章属于“过去”，整段跳过。 */
export function eraPast(pick: string | undefined, era: number): boolean {
  return eraIndex(pick) > era
}

export function originIs(pick: string | undefined, ...names: string[]): boolean {
  const label = pick ? labelOf(pick) : ''
  return names.some((name) => label.includes(name))
}

export function isLowMoral(label: string): boolean {
  return label.startsWith('D') || label.startsWith('E')
}

